"""Download the real manufacturer specification documents listed in data/specs/*.meta.json.

The documents belong to their manufacturers and are not stored in this repository; each sidecar
records where its document came from. Run once after cloning:

    python scripts/fetch_real_specs.py
"""
import json
from pathlib import Path

import httpx

SPECS = Path(__file__).resolve().parents[1] / "data" / "specs"
UA = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"}

with httpx.Client(headers=UA, follow_redirects=True, timeout=60) as client:
    for meta_path in sorted(SPECS.glob("*.meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        if "download_url" not in meta:
            continue  # the fictional demo sheets are generated by make_demo_specs.py
        target = SPECS / meta["file"]
        if target.exists():
            print("have   ", target.name)
            continue
        response = client.get(meta["download_url"])
        if response.status_code != 200 or (target.suffix == ".pdf" and not response.content.startswith(b"%PDF")):
            print("FAILED ", target.name, response.status_code, meta["download_url"])
            continue
        target.write_bytes(response.content)
        print("fetched", target.name, len(response.content), "bytes")
